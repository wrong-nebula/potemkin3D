#!/usr/bin/env node
// Take the camera shaders of the loft walk-through (src/demo/loftwalk.js) as a module this viewer can import:
//   node experiments/luxor-view/take-film.mjs
// They are cut out of that file as they stand there (depth of field, motion blur, bloom, the lens flare, the
// exposure meter, sharpening, the final grade with its AgX curve, fringe, vignette and grain, and the lens dirt
// texture), so this viewer films with the same lens. Run it again when the loft's shaders change.
import fs from 'node:fs';
import path from 'node:path';

const here = import.meta.dirname;
const lines = fs.readFileSync(path.join(here, '../../src/demo/loftwalk.js'), 'utf8').split('\n');
const at = (start) => { const k = lines.findIndex((l) => l.startsWith(start)); if (k < 0) throw new Error(`loftwalk.js has no line starting "${start}"`); return k; };
const head = lines.slice(at('const VERT ='), at('const mat =') + 1);
const body = lines.slice(at('const COMMON ='), at('// ---------------------------------------------------------------- the frame, pass by pass'));
const names = [...head, ...body].map((l) => /^(?:const|function) (\w+)/.exec(l)?.[1]).filter(Boolean);
fs.writeFileSync(path.join(here, 'film.js'), [
  '// Generated by take-film.mjs from src/demo/loftwalk.js: the loft walk-through\'s camera shaders, as they are there.',
  '// Do not edit; run take-film.mjs again instead.',
  "import * as THREE from 'three';",
  '',
  ...head, '', ...body,
  `export { ${names.join(', ')} };`, '',
].join('\n'));
console.log(`film.js: ${names.join(', ')}`);
